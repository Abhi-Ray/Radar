/** The board slug as the pipeline reads it from a source config (see `atsSlugFor`). */
export function companyBoardSlug(c: Pick<SeedCompany, 'config'>): string {
  for (const k of ['board', 'company', 'org', 'slug', 'companyId']) {
    const v = c.config[k];
    if (typeof v === 'string' && v.trim()) return v.trim().toLowerCase();
  }
  throw new Error('company config has no board slug');
}

/** Source instance for a company board (status 'trial', linked to the company at seed time). */
export function companySource(c: SeedCompany): SeedSource {
  const parts = [`${c.check.jobs} open postings (${c.check.security} security, ${c.check.cloud} cloud by title)`];
  if (c.config.query) parts.push(`narrowed to the keyword "${String(c.config.query)}" (big board)`);
  if (c.check.note) parts.push(c.check.note);
  const hint = c.singleCountry ? `country hint ${c.hubCountry}` : `hub ${c.hubCountry}, no country hint (multinational board)`;
  return {
    platformKey: c.platform,
    config: c.config,
    label: `${c.name} (${c.platform})`,
    countryIso2: c.singleCountry ? c.hubCountry : null,
    notes: `Seeded 2026-09-30 as trial: runs, but is not live until the spec §7.4 checklist is done. Board checked ${c.check.at.slice(0, 10)} by the build assistant: ${parts.join('; ')}. ${hint}.`,
  };
}
